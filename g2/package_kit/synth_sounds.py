"""Deterministic synthesis of the kit's original cue sounds (standard library only).

Run ``python3 g2/package_kit/synth_sounds.py`` to regenerate ``sounds/*.wav`` and refresh the hashes in
``kit.json``. Replacing a sound with a licensed recording only needs the file and its kit.json entry.
"""
from __future__ import annotations

import hashlib
import json
import math
import struct
import sys
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parent
RATE = 48000


def synth_sting() -> list[int]:
    """A short bright three-note rising chime (A5, C#6, E6) with exponential decay, mono 16-bit."""
    notes = [(880.0, 0.00), (1108.73, 0.11), (1318.51, 0.22)]
    seconds = 1.0
    total = int(RATE * seconds)
    out = []
    for i in range(total):
        t = i / RATE
        value = 0.0
        for freq, start in notes:
            if t < start:
                continue
            age = t - start
            envelope = min(1.0, age / 0.004) * math.exp(-age * 5.5)
            value += envelope * (math.sin(2 * math.pi * freq * age) + 0.25 * math.sin(4 * math.pi * freq * age))
        fade = min(1.0, (seconds - t) / 0.08)
        out.append(max(-32767, min(32767, round(value * fade * 0.28 * 32767))))
    return out


SOUNDS = {"synth_sting": ("sounds/synth_sting.wav", synth_sting,
                          "原创合成：三个正弦音及泛音的上行短铃音，由 g2/package_kit/synth_sounds.py 生成")}


def write_wav(path: Path, samples: list[int]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(path), "wb") as stream:
        stream.setnchannels(1)
        stream.setsampwidth(2)
        stream.setframerate(RATE)
        stream.writeframes(struct.pack(f"<{len(samples)}h", *samples))


def main() -> None:
    entries = []
    for name, (file, generator, description) in SOUNDS.items():
        samples = generator()
        write_wav(ROOT / file, samples)
        entries.append({"name": name, "file": file, "description": description,
                        "source": "synthesised by g2/package_kit/synth_sounds.py (deterministic, no third-party audio)",
                        "license": "Original work generated by this repository's script; no third-party rights. Same terms as the repository.",
                        "author": "AutoVideo", "sample_rate": RATE, "channels": 1,
                        "duration_seconds": len(samples) / RATE,
                        "sha256": hashlib.sha256((ROOT / file).read_bytes()).hexdigest()})
    (ROOT / "kit.json").write_text(json.dumps({"kit": "autovideo-default", "version": 1, "sounds": entries},
                                              ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("wrote", [e["name"] for e in entries])


if __name__ == "__main__":
    sys.exit(main())
