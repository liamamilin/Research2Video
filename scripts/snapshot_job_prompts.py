"""Take the snapshot tests/test_matrices.py compares against: each Job's rendered prompt and fallback keywords, hashed.

Run it after editing a Job's prompt on purpose (python scripts/snapshot_job_prompts.py, from the repo root). The
snapshot fixes the date and leaves event memory and outcomes as placeholders, so only the Job file and its matrix count.
"""

from __future__ import annotations

import hashlib
import json
import os
import sys
from datetime import datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from core import matrices  # noqa: E402
from core.config import list_jobs, load_job  # noqa: E402
from core.engine import ResearchEngine  # noqa: E402

FIXTURE = os.path.join(ROOT, "tests", "fixtures", "job_prompt_hashes.json")


def main() -> None:
    config, jobs = os.path.join(ROOT, "config"), os.path.join(ROOT, "jobs")
    engine = ResearchEngine.__new__(ResearchEngine)
    engine.config_dir, engine.prompt_vars = config, {}
    engine._now = lambda: datetime(2026, 10, 20, 8, 0, 0)
    engine._reported_events = lambda: "<<events>>"
    engine._outcomes_block = lambda: "<<outcomes>>"
    out = {}
    for name in list_jobs(jobs):
        if name.startswith(("video/", "vod/")):  # generated by the video pipeline
            continue
        job = load_job(jobs, name)
        if not job or not job.get("prompt"):
            continue
        run = matrices.for_run(job, config)
        text = engine._build_prompt(run) + "\n--fallback--\n" + json.dumps(run.get("keywords", []), ensure_ascii=False)
        out[name] = hashlib.sha256(text.encode()).hexdigest()
    with open(FIXTURE, "w", encoding="utf-8") as fh:
        json.dump(out, fh, ensure_ascii=False, indent=1, sort_keys=True)
    print(f"{len(out)} Jobs -> {os.path.relpath(FIXTURE, ROOT)}")


if __name__ == "__main__":
    main()
