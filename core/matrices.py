"""Matrices: a named set of research Jobs sharing a domain and keywords (spec/product-redesign.md §2.1, spec/matrices.md).

One file per matrix, ``config/matrices/<key>.yaml``::

    name: 医疗矩阵
    domain: 医疗健康            # the prompt's {domain}
    keywords: [新药审批, 医保政策] # every member Job's {keywords} starts with these, then its own
    jobs:
      - medical/flash_discovery
      - job: monitoring/ai_flash_discovery
        copy_as: _flash_discovery   # copying the matrix makes this Job from that template instead (its prompt says AI)

Membership lives here only, so a Job file never changes when it joins or leaves a matrix. A Job belongs to at most one
matrix. The engine applies the matrix when it runs a member (``for_run``); the web layer reads Jobs without it, so the
Job editor never saves the matrix's keywords into the Job file.
"""

from __future__ import annotations

import os
import re
from dataclasses import dataclass, field
from typing import Optional

import yaml

from .fileio import atomic_write

KEY = re.compile(r"[a-z][a-z0-9_]{0,23}")
#: generated by the video pipeline, not research Jobs anyone groups
_GENERATED = ("video/", "vod/")


@dataclass(frozen=True)
class Member:
    job: str
    copy_as: str = ""    # a template under jobs/_templates the copy is made from; empty: the Job is copied as it is


@dataclass(frozen=True)
class Matrix:
    key: str
    name: str
    domain: str = ""
    keywords: tuple = ()
    members: tuple = ()  # Member, in the file's order
    errors: tuple = ()

    @property
    def jobs(self) -> list[str]:
        return [m.job for m in self.members]

    def as_dict(self) -> dict:
        return {"key": self.key, "name": self.name, "domain": self.domain, "keywords": list(self.keywords),
                "jobs": [{"job": m.job, "copy_as": m.copy_as} for m in self.members], "errors": list(self.errors)}


def directory(config_dir: str) -> str:
    return os.path.join(config_dir, "matrices")


def _strings(value) -> list[str]:
    out: list[str] = []
    for item in value or []:
        text = str(item).strip()
        if text and text not in out:
            out.append(text)
    return out


def _read(path: str, key: str) -> Matrix:
    errors: list[str] = []
    try:
        with open(path, encoding="utf-8") as fh:
            data = yaml.safe_load(fh) or {}
    except (OSError, yaml.YAMLError) as exc:
        return Matrix(key=key, name=key, errors=(f"读不了：{str(exc)[:120]}",))
    if not isinstance(data, dict):
        return Matrix(key=key, name=key, errors=("应为映射（name、domain、keywords、jobs）",))
    members: list[Member] = []
    for item in data.get("jobs") or []:
        if isinstance(item, dict):
            member = Member(job=str(item.get("job") or "").strip(), copy_as=str(item.get("copy_as") or "").strip())
        else:
            member = Member(job=str(item).strip())
        if not member.job:
            continue
        if member.job.startswith(_GENERATED):
            errors.append(f"{member.job} 是视频流水线生成的 Job，不能放进矩阵")
            continue
        if member.job not in [m.job for m in members]:
            members.append(member)
    unknown = set(data) - {"name", "domain", "keywords", "jobs"}
    if unknown:
        errors.append(f"不认识的字段：{', '.join(sorted(unknown))}")
    return Matrix(key=key, name=str(data.get("name") or key).strip(), domain=str(data.get("domain") or "").strip(),
                  keywords=tuple(_strings(data.get("keywords"))), members=tuple(members), errors=tuple(errors))


def load_all(config_dir: str = "config") -> dict[str, Matrix]:
    """Every matrix, by key, in file-name order. A Job claimed by an earlier matrix is an error in the later one."""
    folder = directory(config_dir)
    try:
        names = sorted(f for f in os.listdir(folder) if f.endswith(".yaml") and not f.startswith("."))
    except OSError:
        return {}
    out: dict[str, Matrix] = {}
    owner: dict[str, str] = {}
    for filename in names:
        key = filename[:-len(".yaml")]
        if not KEY.fullmatch(key):
            continue
        matrix = _read(os.path.join(folder, filename), key)
        kept, errors = [], list(matrix.errors)
        for member in matrix.members:
            if member.job in owner:
                errors.append(f"{member.job} 已经在「{out[owner[member.job]].name}」里：一个 Job 只能属于一个矩阵")
                continue
            owner[member.job] = key
            kept.append(member)
        out[key] = Matrix(**{**matrix.__dict__, "members": tuple(kept), "errors": tuple(errors)})
    return out


def of_job(job_name: str, config_dir: str = "config") -> Optional[Matrix]:
    return next((m for m in load_all(config_dir).values() if job_name in m.jobs), None)


def merged_keywords(matrix: Optional[Matrix], own) -> list:
    """The matrix's keywords first, then the Job's own that are not already there (spec decision 4)."""
    own = list(own or [])
    if matrix is None or not matrix.keywords:
        return own
    return list(matrix.keywords) + [k for k in own if k not in matrix.keywords]


def for_run(job: dict, config_dir: str = "config") -> dict:
    """The Job as a run sees it: matrix keywords merged in, ``_domain`` and ``_matrix`` set. Not a member: unchanged."""
    try:
        matrix = of_job(job.get("_file", ""), config_dir)
    except Exception:  # noqa: BLE001 - a broken matrix file must not stop a run
        matrix = None
    if matrix is None:
        return job
    out = dict(job)
    out["keywords"] = merged_keywords(matrix, job.get("keywords"))
    out["_matrix"] = matrix.key
    if matrix.domain:
        out["_domain"] = matrix.domain
    return out


def jobs_of_other_matrices(job_name: str, config_dir: str = "config") -> set[str]:
    """Members of every matrix the Job is not in: their sources are left out of its event memory.

    A Job in no matrix (the video pipeline's research, a Job not grouped yet) keeps reading all of it, as before.
    """
    try:
        every = list(load_all(config_dir).values())
    except Exception:  # noqa: BLE001 - no matrices readable: nothing to leave out
        return set()
    if not any(job_name in m.jobs for m in every):
        return set()
    return {j for m in every if job_name not in m.jobs for j in m.jobs}


def save(config_dir: str, key: str, *, name: str, domain: str, keywords, members) -> None:
    data = {"name": name, "domain": domain, "keywords": _strings(keywords),
            "jobs": [m.job if not m.copy_as else {"job": m.job, "copy_as": m.copy_as} for m in members]}
    text = ("# 矩阵：一组 Job，共用一个领域和一套关键词（spec/matrices.md）。成员 Job 运行时，{keywords} 先放这里的关键词，\n"
            "# 再放 Job 自己的；{domain} 是这里的 domain。\n"
            + yaml.safe_dump(data, allow_unicode=True, sort_keys=False, default_flow_style=False))
    os.makedirs(directory(config_dir), exist_ok=True)
    atomic_write(os.path.join(directory(config_dir), f"{key}.yaml"), text)


def remove(config_dir: str, key: str) -> bool:
    try:
        os.remove(os.path.join(directory(config_dir), f"{key}.yaml"))
        return True
    except FileNotFoundError:
        return False
